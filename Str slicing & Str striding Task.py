# a-0 r-1 t-2 i-3 f-4 i-5 c-6 i-7 a-8 l-9
text = "artificial"
print(text[:5])      # artif
print(text[5:])      # icial
print(text[2:8])     # tifici
print(text[-4:])     # icial
print(text[:-3])     # artific
print(text[::2])     # atfca
print(text[1::2])    # riiil
print(text[::-1])    # laicifitra
print(text[::-2])    # liciat


